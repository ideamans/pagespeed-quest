#!/usr/bin/env node
/**
 * Generate llmdocs/90-commands.md from the actual `psq` command tree.
 *
 * Run through `yarn build` (and `yarn ai:regen`) after `tsc`, because it walks
 * the compiled command definitions rather than a hand-written list. Never edit
 * llmdocs/90-commands.md by hand — change the command definitions in
 * src/cli.ts and run this again.
 */

import { readFile, writeFile } from 'fs/promises'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const projectRoot = join(__dirname, '..')
const outputPath = join(projectRoot, 'llmdocs', '90-commands.md')

const { createProgram } = await import(join(projectRoot, 'build', 'cli.js'))

function walk(command, path, depth, lines) {
  const heading = '#'.repeat(Math.min(depth + 1, 6))
  const title = [...path, command.name()].join(' ')

  lines.push(`${heading} ${title}`)
  lines.push('')
  const description = command.description()
  if (description) {
    lines.push(description)
    lines.push('')
  }
  lines.push('```')
  lines.push(command.helpInformation().trimEnd())
  lines.push('```')
  lines.push('')

  for (const child of command.commands) {
    walk(child, [...path, command.name()], depth + 1, lines)
  }
}

const program = createProgram()

const lines = [
  '# Command catalog',
  '',
  '<!-- Generated by scripts/build-llm-docs.js. Do not edit by hand. -->',
  '',
  'Options belong to the command they are declared on, so they must appear',
  'before the next subcommand: `psq -i <dir> lighthouse -a <dir> playback`.',
  '',
]

walk(program, [], 1, lines)

const generated = `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== generated) {
    process.stderr.write(
      `llmdocs/90-commands.md is out of date with the command definitions.\nRun \`yarn ai:regen\` and commit the result — do not edit it by hand.\n`
    )
    process.exit(1)
  }
  process.stdout.write('llmdocs/90-commands.md is up to date\n')
} else {
  await writeFile(outputPath, generated)
  process.stdout.write(`Wrote ${outputPath}\n`)
}
